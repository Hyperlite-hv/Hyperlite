def english(name):
    if name in WHOLE:
        return WHOLE[name]
    parts = name.split("_")
    if parts[-1] == "le" and len(parts) > 1:  # cree_le, verifie_le: when it happened
        return "_".join(WORDS.get(p, WHOLE.get(p, p)) for p in parts[:-1]) + "_at"
    out = []
    i = 0
    while i < len(parts):
        two = "_".join(parts[i : i + 2])
        if i + 1 < len(parts) and two in WHOLE:
            out.append(WHOLE[two])
            i += 2
            continue
        out.append(WORDS.get(parts[i], WHOLE.get(parts[i], parts[i])))
        i += 1
    return "_".join(out)


def main():
    inventory = json.loads((HERE / "inventory.json").read_text())
    names, rows, left = {}, [], set()
    from extract import FRENCH

    for old, info in inventory.items():
        if old in NOT_FRENCH:
            continue
        new = english(old)
        names[old] = new
        left |= {p for p in new.split("_") if p in FRENCH and p not in WORDS.values() and p not in WHOLE.values()}
        rows.append((", ".join(info["kinds"]), old, new, info["seen"], info["where"][0]))
    (HERE / "names.json").write_text(json.dumps(names, indent=1, ensure_ascii=False, sort_keys=True) + "\n")
    order = {"column": 0, "table": 0, "path": 1, "field": 2, "string": 3}
    rows.sort(key=lambda r: (min(order[k] for k in r[0].split(", ")), r[1]))
    lines = [
        "# API v1 glossary (proposed)",
        "",
        "Generated by `translate.py` from `inventory.json` (`extract.py`). Kinds: `column`/`table` of the database,",
        "`path` word of a route, `field` of a request, `string` constant of the code (a JSON key or a stored value).",
        f"{len(rows)} names. Correct a line by editing `WHOLE` or `WORDS` in `translate.py`, then run it again.",
        "",
        "| Kind | Today | Proposed | Files | First seen in |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {k} | `{o}` | `{n}` | {s} | `{w}` |" for k, o, n, s, w in rows]
    lines += [
        "",
        "## Values that depend on their field",
        "",
        "A few French values mean two things. The migration translates them by field, never by value alone:",
        "",
        "| Value | Field | v1 |",
        "| --- | --- | --- |",
        "| `actif` | a VM's or a container's `etat` | `running` |",
        "| `actif` | a pool's or a storage's `etat`, a setting's `actif` | `active` / `enabled` |",
        "| `arrete`, `arretee` | a VM's `etat` | `stopped` |",
        "| `termine`, `reussi` | a task's `statut`, a job run's `reussi` | `succeeded` |",
        "| `echec` | a task's `statut`, an audit `result` | `failed` |",
        "",
        "`hl_docs`, `hl_sso_binding`, `hl_sso_handoff` are cookie names, kept. `vlan` is English.",
    ]
    (HERE / "glossary.md").write_text("\n".join(lines) + "\n")
    print(len(rows), "names;", "still French:", sorted(left))


if __name__ == "__main__":
    main()
