"""requirements.txt is generated from requirements.in by pip-compile, every package pinned with its hashes, for the
Python of Debian 13 (docs/design/clean-package.md). Checked without network: a dependency added to requirements.in
but not compiled, a pin changed by hand, or a package without hashes fails here."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = re.compile(r"^([A-Za-z0-9_.\-]+)(?:\[[^\]]*\])?==(\S+)", re.M)


def _pins(text):
    return {name.lower().replace("_", "-"): version for name, version in PIN.findall(text)}


def test_every_dependency_of_requirements_in_is_pinned_the_same_in_requirements_txt():
    wanted = _pins((ROOT / "requirements.in").read_text())
    locked = _pins((ROOT / "requirements.txt").read_text())
    assert wanted, "requirements.in lists no pinned dependency"
    assert {name: version for name, version in wanted.items() if locked.get(name) != version} == {}


def test_every_locked_package_has_its_hashes_and_the_file_is_pip_compiles_for_python_3_13():
    text = (ROOT / "requirements.txt").read_text()
    assert "autogenerated by pip-compile with Python 3.13" in text
    blocks = [b for b in re.split(r"\n(?=[A-Za-z0-9])", text) if PIN.match(b)]  # one block per package
    assert len(blocks) == len(_pins(text))
    assert [b.split()[0] for b in blocks if "--hash=sha256:" not in b] == []
    assert "pip==" in text  # postinst installs pip from this file too, never the newest of the day
